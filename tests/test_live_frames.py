def test_start_offset_shifts_grab_time_exactly(tmp_path, monkeypatch, fake_ffmpeg, no_ocr):
    _fixed_edges(monkeypatch, {'video_mon0.mp4': 30.0})
    seeks = []
    for off in (0.0, 0.3):
        sid, store, service = _env([_track(tmp_path / 'video_mon0.mp4', start_offset_sec=off)])
        fake_ffmpeg.clear()
        fr = lf.frame_at(sid, 5.0, store=store, service=service, ffmpeg='ffmpeg')
        assert fr['t'] == 5.0 and fr['video_t'] == pytest.approx(5.0 - off)
        seeks.append(_seek_of(fake_ffmpeg[0]))
    assert seeks[0] - seeks[1] == pytest.approx(0.3, abs=1e-3)


def test_segments_map_timeline_into_their_files(tmp_path, monkeypatch, fake_ffmpeg, no_ocr):
    _fixed_edges(monkeypatch, {'video_mon0.mp4': 30.0, 'video_mon0_seg1.mp4': 20.0})
    a, b = str(tmp_path / 'video_mon0.mp4'), str(tmp_path / 'video_mon0_seg1.mp4')
    track = _track(b, start_offset_sec=40.0,
                   segments=[{'n': 0, 'path': a, 'start_offset_sec': 0.0},
                             {'n': 1, 'path': b, 'start_offset_sec': 40.0}])
    sid, store, service = _env([track])

    fr = lf.frame_at(sid, 10.0, store=store, service=service)
    assert fr['segment'] == 0 and fr['video_t'] == pytest.approx(10.0)
    assert fake_ffmpeg[-1][fake_ffmpeg[-1].index('-i') + 1] == a

    fr = lf.frame_at(sid, 45.0, store=store, service=service)
    assert fr['segment'] == 1 and fr['video_t'] == pytest.approx(5.0)
    assert fake_ffmpeg[-1][fake_ffmpeg[-1].index('-i') + 1] == b
    assert abs(_seek_of(fake_ffmpeg[-1]) - 5.0) < 1 / 30

    with pytest.raises(lf.LiveFramesError) as e:
        lf.frame_at(sid, 35.0, store=store, service=service)
    assert e.value.code == 'NOT_RECORDED'
    assert e.value.extra['readable_ranges'] == [[0.0, 30.0], [40.0, 60.0]]
    with pytest.raises(lf.LiveFramesError) as e:
        lf.frame_at(sid, 61.0, store=store, service=service)
    assert e.value.code == 'PAST_LIVE_EDGE' and e.value.extra['readable_until'] == 60.0


