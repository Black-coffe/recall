FFMPEG = shutil.which('ffmpeg')
FFPROBE = shutil.which('ffprobe')
needs_ffmpeg = pytest.mark.skipif(FFMPEG is None or FFPROBE is None, reason='ffmpeg not in PATH')
MOVFLAGS = '+frag_keyframe+empty_moov+default_base_moof'


class FakeStore:
    def __init__(self, manifests):
        self.manifests = manifests

    def read(self, sid):
        if sid not in self.manifests:
            raise RuntimeError(f'no session {sid}')
        return self.manifests[sid]


class FakeService:
    def __init__(self, states):
        self.states = states

    def get_state(self, sid):
        return self.states[sid]


def _env(tracks, *, status='recording', active=True, sid='rec_a'):
    manifest = {'status': status, 'streams': {'video': tracks}}
    state = {'status': status, 'is_active': active, 'elapsed_seconds': 99.0}
    return sid, FakeStore({sid: manifest}), FakeService({sid: state})


def _track(path, **kw):
    return {'track_id': kw.pop('track_id', 'mon0'), 'monitor_index': kw.pop('monitor_index', 0),
            'monitor_label': 'Monitor', 'fps': kw.pop('fps', 30), 'path': str(path),
            'start_offset_sec': kw.pop('start_offset_sec', 0.0), 'status': 'recording', **kw}


def _make_fmp4(path, src, *, gop=30):
    subprocess.run([FFMPEG, '-v', 'error', '-y', '-f', 'lavfi', '-i', src, '-c:v', 'libx264',
                    '-qp', '0', '-g', str(gop), '-pix_fmt', 'yuv420p', '-movflags', MOVFLAGS,
                    str(path)], check=True)
    return str(path)


def _top_boxes(data):
    pos, out = 0, []
    while pos + 8 <= len(data):
        size, kind = struct.unpack('>I4s', data[pos:pos + 8])
        out.append((kind.decode(), pos, size))
        pos += size
    return out


def _ffprobe_duration(path):
    r = subprocess.run([FFPROBE, '-v', 'error', '-show_entries', 'format=duration', '-of',
                        'default=nw=1:nk=1', path], capture_output=True, text=True)
    return float(r.stdout.strip())


