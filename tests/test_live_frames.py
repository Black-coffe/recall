def test_changes_mode_cursor_crosses_a_pause(tmp_path, monkeypatch):
    """A cursor at the end of a segment before a pause moves into the next segment."""
    _fixed_edges(monkeypatch, {'video_mon0.mp4': 30.0, 'video_mon0_seg1.mp4': 20.0})
    monkeypatch.setattr(lf, '_render', lambda track, seg, t, size, ffmpeg:
                        {'t': round(t, 4), 'segment': seg['n']})
    scanned_files = []

    def _flat_thumbs(path, duration, *, fps=1.0, ffmpeg=None, start=None, window=None,
                     progress=None):
        scanned_files.append(os.path.basename(path))
        n = max(1, int(round(duration * fps)) + 1)
        return np.full((n, vf.THUMB_H, vf.THUMB_W), 128, dtype=np.uint8)
    monkeypatch.setattr(vf, 'thumbs_pass', _flat_thumbs)
    a, b = str(tmp_path / 'video_mon0.mp4'), str(tmp_path / 'video_mon0_seg1.mp4')
    track = _track(b, start_offset_sec=40.0,
                   segments=[{'n': 0, 'path': a, 'start_offset_sec': 0.0},
                             {'n': 1, 'path': b, 'start_offset_sec': 40.0}])
    sid, store, service = _env([track])

    cursor, seen = None, []
    for _ in range(5):
        res = lf.frames_range(sid, 0.0, 60.0, mode='changes', limit=12, cursor=cursor,
                              store=store, service=service, ffmpeg='ffmpeg')
        assert res['next_t'] is None or res['next_t'] != cursor, 'cursor stalled'
        seen.append(res['scanned_until'])
        cursor = res['next_t']
        if cursor is None:
            break
    assert cursor is None and seen[-1] == pytest.approx(60.0)
    assert scanned_files == ['video_mon0.mp4', 'video_mon0_seg1.mp4']


