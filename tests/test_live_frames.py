@needs_ffmpeg
def test_readable_until_stops_at_last_complete_fragment(tmp_path, no_ocr):
    full = _make_fmp4(tmp_path / 'full.mp4', 'testsrc2=s=640x360:r=30:d=6', gop=60)
    data = open(full, 'rb').read()
    boxes = _top_boxes(data)
    last_moof = [b for b in boxes if b[0] == 'moof'][-1]
    cut = last_moof[1] + last_moof[2] + 200          # inside the last fragment's mdat
    part = tmp_path / 'video_mon0.mp4'
    part.write_bytes(data[:cut])

    edge = lf.readable_until(str(part))
    assert edge is not None and 0 < edge <= 6.0 - 1.0, edge
    assert lf.readable_until(full) == pytest.approx(6.0, abs=0.05)
    assert _ffprobe_duration(str(part)) > edge

    sid, store, service = _env([_track(part)])
    fr = lf.frame_at(sid, edge - 0.1, store=store, service=service, ffmpeg=FFMPEG)
    assert fr['jpeg'][:2] == b'\xff\xd8' and fr['ocr'] is False and fr['text'] is None
    with pytest.raises(lf.LiveFramesError) as e:
        lf.frame_at(sid, edge + 0.5, store=store, service=service, ffmpeg=FFMPEG)
    assert e.value.code == 'PAST_LIVE_EDGE'
    assert e.value.extra['readable_until'] == pytest.approx(edge)
    assert e.value.extra['track_id'] == 'mon0'


