@needs_ffmpeg
def test_changes_mode_finds_three_changes_and_clamps_end(tmp_path, blank_ocr):
    scenes = [('red', 5), ('blue', 6), ('green', 6), ('white', 6)]
    args = [FFMPEG, '-v', 'error', '-y']
    for color, dur in scenes:
        args += ['-f', 'lavfi', '-i', f'color=c={color}:s=320x180:r=10:d={dur}']
    chain = ''.join(f'[{i}:v]' for i in range(4)) + 'concat=n=4:v=1:a=0[v]'
    v = str(tmp_path / 'video_mon0.mp4')
    subprocess.run(args + ['-filter_complex', chain, '-map', '[v]', '-pix_fmt', 'yuv420p',
                           '-g', '20', '-movflags', MOVFLAGS, v], check=True)
    sid, store, service = _env([_track(v, fps=10)])
    res = lf.frames_range(sid, 0.0, 500.0, mode='changes', limit=12,
                          store=store, service=service, ffmpeg=FFMPEG)
    assert res['end_clamped'] is True and res['end'] == pytest.approx(res['readable_until'])
    assert [round(f['change_t']) for f in res['frames']] == [5, 11, 17]
    assert res['next_t'] is not None and res['scanned_until'] is not None


