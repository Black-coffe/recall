def test_status_and_session_errors(tmp_path, monkeypatch, fake_ffmpeg, no_ocr):
    _fixed_edges(monkeypatch, {'video_mon0.mp4': 12.5, 'video_mon1.mp4': None})
    tracks = [_track(tmp_path / 'video_mon0.mp4', start_offset_sec=0.5),
              _track(tmp_path / 'video_mon1.mp4', track_id='mon1', monitor_index=1, fps=15)]
    sid, store, service = _env(tracks)
    st = lf.status(sid, store=store, service=service)
    assert st['available'] is True and st['reason'] is None
    assert [(t['track_id'], t['monitor_index'], t['fps'], t['readable_until'])
            for t in st['tracks']] == [('mon0', 0, 30.0, 13.0), ('mon1', 1, 15.0, None)]
    assert st['tracks'][0]['segments'] == [{'n': 0, 'start': 0.5, 'readable_until': 13.0}]
    assert st['tracks'][0]['segments_unmapped'] == 0

    with pytest.raises(lf.LiveFramesError) as e:
        lf.frame_at(sid, 1.0, store=store, service=service)
    assert e.value.code == 'INVALID_ARGUMENT' and e.value.extra['track_ids'] == ['mon0', 'mon1']

    with pytest.raises(lf.LiveFramesError) as e:
        lf.status('rec_missing', store=store, service=service)
    assert e.value.code == 'NOT_FOUND'

    sid2, store2, service2 = _env([])
    with pytest.raises(lf.LiveFramesError) as e:
        lf.status(sid2, store=store2, service=service2)
    assert e.value.code == 'NO_VIDEO'

    sid3, store3, service3 = _env(tracks, status='finalized', active=False)
    st3 = lf.status(sid3, store=store3, service=service3)
    assert st3['available'] is False and st3['reason'] == 'finalized'
    assert lf.frame_at(sid3, 1.0, store=store3, service=service3)['available'] is False


