@pytest.fixture
def fake_ffmpeg(monkeypatch):
    """subprocess.run of video_frames → a 320x180 white PNG; records every argv."""
    calls = []
    buf = BytesIO()
    Image.new('RGB', (320, 180), (255, 255, 255)).save(buf, 'PNG')

    def _run(cmd, **kw):
        calls.append(list(cmd))
        return SimpleNamespace(returncode=0, stdout=buf.getvalue(), stderr=b'')
    monkeypatch.setattr(vf.subprocess, 'run', _run)
    return calls


def _seek_of(argv):
    return float(argv[argv.index('-ss') + 1])


def _fixed_edges(monkeypatch, edges):
    monkeypatch.setattr(lf, 'readable_until', lambda p: edges.get(os.path.basename(p)))


