@needs_ffmpeg
def test_session_dir_unchanged_by_calls(tmp_path, blank_ocr):
    sess = tmp_path / 'rec_a'
    sess.mkdir()
    v = _make_fmp4(sess / 'video_mon0.mp4', 'testsrc2=s=320x180:r=10:d=4', gop=10)

    def snap():
        return {p: hashlib.sha256(open(os.path.join(sess, p), 'rb').read()).hexdigest()
                for p in sorted(os.listdir(sess))}
    before = snap()
    sid, store, service = _env([_track(v, fps=10)])
    lf.status(sid, store=store, service=service)
    lf.frame_at(sid, 1.0, store=store, service=service, ffmpeg=FFMPEG)
    lf.frames_range(sid, 0.0, 3.0, mode='changes', store=store, service=service, ffmpeg=FFMPEG)
    lf.frames_range(sid, 0.0, 3.0, mode='step', store=store, service=service, ffmpeg=FFMPEG)
    assert snap() == before
