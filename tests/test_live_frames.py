def _frame_index(fr):
    return int(round(np.asarray(Image.open(BytesIO(fr['jpeg'])).convert('L')).mean() / 16))


@needs_ffmpeg
def test_step_one_frame_pages_without_repeats(tmp_path, blank_ocr):
    v = _make_fmp4(tmp_path / 'video_mon0.mp4',
                   "color=black:s=128x72:r=30:d=3,format=gray,geq=lum='mod(N,16)*16'")
    sid, store, service = _env([_track(v)])
    res = lf.frames_range(sid, 0.0, 2.0, mode='step', step=1 / 30, limit=40,
                          store=store, service=service, ffmpeg=FFMPEG)
    assert res['count'] == 12 and res['truncated'] is True
    assert [_frame_index(f) for f in res['frames']] == list(range(12))
    assert res['next_t'] == pytest.approx(res['frames'][-1]['t'] + 1 / 30, abs=1e-3)
    res2 = lf.frames_range(sid, None, 2.0, mode='step', step=1 / 30, limit=4,
                           cursor=res['next_t'], store=store, service=service, ffmpeg=FFMPEG)
    assert [_frame_index(f) for f in res2['frames']] == [12, 13, 14, 15]


