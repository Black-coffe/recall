#!/usr/bin/env bash
# VULYK defect library index - generates docs/defects/INDEX.md from the cards (parser: .claude/hooks/defects_lib.py).
#
#   Usage: bash scripts/defects-index.sh                 # write INDEX.md
#          bash scripts/defects-index.sh --check         # exit 1 and print `index stale` when INDEX.md differs
#          bash scripts/defects-index.sh --grep <regex>  # <ref>:<line>: <text> over cards only, case-insensitive
#          bash scripts/defects-index.sh --counts        # cards <n> · never <n> · allowed <n> · how-to <n> · allowed repeats <n>
#
# INDEX.md: a header, then three tables `## Never`, `## Allowed`, `## How-to`; a card is a row in each table
# where it has lines, sorted by area then ref. `repeats` = dated Allowed lines - 1 in the Allowed table, owner
# quotes - 1 elsewhere (never below 0). Counts are over live (not revoked) cards.
# Exit: 0 done (--check: fresh; --grep: a match), 1 stale (--check) or no match (--grep), 2 usage / no library /
# no python / no parser / a bad regex. DEFECTS_DIR overrides docs/defects (relative to the repo root, or absolute).
set -uo pipefail

MODE=write; PAT=""
case "${1:-}" in
  -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  '') [ "$#" -eq 0 ] || { echo "defects-index: empty argument" >&2; exit 2; } ;;
  --check) MODE=check ;;
  --counts) MODE=counts ;;
  --grep) MODE=grep; [ "$#" -eq 2 ] && [ -n "$2" ] || { echo "defects-index: usage: --grep <regex>" >&2; exit 2; }; PAT="$2" ;;
  *) echo "defects-index: usage: bash scripts/defects-index.sh [--check | --counts | --grep <regex>]" >&2; exit 2 ;;
esac
if [ "$MODE" != grep ] && [ "$#" -gt 1 ]; then
  echo "defects-index: usage: bash scripts/defects-index.sh [--check | --counts | --grep <regex>]" >&2; exit 2
fi

LIB="$(cd "$(dirname "$0")/../.claude/hooks" 2>/dev/null && pwd)"
[ -f "$LIB/defects_lib.py" ] || { echo "defects-index: card parser missing: $(dirname "$0")/../.claude/hooks/defects_lib.py" >&2; exit 2; }

ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
cd "$ROOT" || exit 2
DIR="${DEFECTS_DIR:-docs/defects}"
[ -d "$DIR" ] || { echo "defects-index: no defect library at $DIR" >&2; exit 2; }

PY=""
for p in python3 python; do
  if command -v "$p" >/dev/null 2>&1 && "$p" -c 'import sys; sys.exit(sys.version_info[0] != 3)' >/dev/null 2>&1; then
    PY="$p"; break
  fi
done
[ -n "$PY" ] || { echo "defects-index: python 3 not found on PATH (python3 or python) - cannot parse cards" >&2; exit 2; }

PYTHONIOENCODING=utf-8 "$PY" - "$MODE" "$DIR" "$LIB" "$PAT" <<'PY'
import os, re, sys

sys.stdout.reconfigure(newline='\n')
mode, d, hooks, pat = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
if os.name == 'nt' and re.match(r'^/[A-Za-z]/', hooks):
    hooks = hooks[1] + ':' + hooks[2:]
sys.path.insert(0, hooks)
import defects_lib

cards = sorted(defects_lib.load_cards(d), key=lambda c: (c.area, c.ref))
live = [c for c in cards if c.status != 'revoked']

def dated(c):
    return [x for x in c.allowed_dates if x]

def counts():
    return 'cards %d · never %d · allowed %d · how-to %d · allowed repeats %d' % (
        len(live), sum(len(c.never) for c in live), sum(len(c.allowed) for c in live),
        sum(len(c.howto) for c in live), sum(max(0, len(dated(c)) - 1) for c in live))

if mode == 'counts':
    print(counts())
    sys.exit(0)

if mode == 'grep':
    try:
        rx = re.compile(pat, re.I)
    except re.error as e:
        sys.stderr.write('defects-index: bad regex: %s\n' % e)
        sys.exit(2)
    hit = False
    for c in cards:
        with open(os.path.join(d, c.path), encoding='utf-8', errors='replace', newline='') as fh:
            for n, line in enumerate(fh.read().lstrip('﻿').split('\n'), 1):
                line = line.rstrip('\r')
                if rx.search(line):
                    print('%s:%d: %s' % (c.ref, n, line))
                    hit = True
    sys.exit(0 if hit else 1)

def cell(s):
    return (s or '-').replace('|', '\\|')

def last(dates):
    dates = [x for x in dates if x]
    return max(dates) if dates else '-'

qdates = lambda c: [q[:10] for q in c.quotes]
out = ['# Defect index', '',
       'Generated by `bash scripts/defects-index.sh` from the cards; never edit by hand. The gate',
       '(`bash scripts/defects-check.sh`) is red while this file differs from the cards. Search the cards:',
       '`bash scripts/defects-index.sh --grep <regex>`. Format: [README.md](README.md).', '',
       counts(), '']
head = '| area | card | title | status | lines | quotes | repeats | last |'
for name, field in (('Never', 'never'), ('Allowed', 'allowed'), ('How-to', 'howto')):
    out += ['## ' + name, '']
    rows = []
    for c in cards:
        lines = getattr(c, field)
        if not lines:
            continue
        if field == 'allowed':
            rep, when = max(0, len(dated(c)) - 1), last(c.allowed_dates)
        else:
            rep, when = max(0, len(c.quotes) - 1), last(qdates(c))
        rows.append('| %s | [%s](%s) | %s | %s | %d | %d | %d | %s |' % (
            c.area, c.ref, c.path, cell(defects_lib.fm_scalar(c.fm.get('title', ''))), c.status,
            len(lines), len(c.quotes), rep, when))
    out += ([head, '|---|---|---|---|---|---|---|---|'] + rows) if rows else ['none']
    out.append('')
text = '\n'.join(out)
index = d.rstrip('/\\') + '/INDEX.md'

if mode == 'check':
    try:
        with open(index, encoding='utf-8', newline='') as fh:
            have = fh.read().replace('\r\n', '\n')
    except OSError:
        have = None
    if have != text:
        print('index stale: %s differs from the cards - regenerate: bash scripts/defects-index.sh' % index)
        sys.exit(1)
    sys.exit(0)

with open(index, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write(text)
print('wrote %s: %s' % (index, counts()))
PY
